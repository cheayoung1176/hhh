export function findAnswer(text) {
  const l = text.toLowerCase();
  const pm = l.match(/p\.(\d+)/);
  if (pm && PAGES[pm[1] - 1]) {
    const n = Number(pm[1]);
    return { a: `p.${n}의 핵심 내용입니다. ${PAGES[n - 1].k}`, s: [n] };
  }
  const hit = QA.find((q) => q.m.some((k) => l.includes(k)));
  if (hit) return { a: hit.a, s: hit.s };
  return {
    a: '질문과 관련된 내용을 이 문서에서 찾지 못했습니다. 다른 표현으로 질문하거나 키워드 탭의 항목을 선택해 보세요.',
    s: [],
    none: true,
  };
}

